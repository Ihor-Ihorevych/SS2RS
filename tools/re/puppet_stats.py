"""Table of the puppet parameter files: health, score and class of every character (read-only).

For every `.ep` under `Databases/Puppets` (and the player puppets): the root class, `SPuppetHealthParams` members `.1` and `.2`,
`CMiscPupeptParams.mpp_slScore`, the character behavior name when the file names one, and the first movement-envelope numbers.
Writes markdown (docs/re/puppet-stats.md) or prints it.

Usage: python -I tools/re/puppet_stats.py [DATA_DIR] [--markdown OUT.md]
"""
import collections, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ctse_values import Obj, Ref, TreeDec, merged_files, parse  # noqa: E402


def find(o, suffix, out):
    for k, v in o:
        if isinstance(v, Obj): find(v, suffix, out)
        elif k.endswith(suffix): out.append(v)


def first(o, suffix):
    out = []; find(o, suffix, out); return out[0] if out else None


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    md = sys.argv[sys.argv.index("--markdown") + 1] if "--markdown" in sys.argv else None
    args = [a for a in args if a != md]
    install = args[0] if args else os.environ.get("SS2_DATA_DIR", "")
    if not install or not os.path.isdir(install): sys.exit("pass the install folder or set SS2_DATA_DIR")
    rows = []
    for name, d in sorted(merged_files(install, ".ep").items()):
        r = parse(d); objs, _ = TreeDec(d, r).objects()
        for o in objs.values():
            if not isinstance(o, Obj) or o.type == "CResourceFile": continue
            score = first(o, "mpp_slScore")
            if score is None: continue
            hp = None
            for k, v in o:
                if k.endswith("SPuppetParams.1") and isinstance(v, Obj): hp = [x for _, x in v][:2]
            rel = name.split("databases/")[-1]
            rows.append((rel.split("/")[1] if rel.startswith("puppets/") and rel.count("/") > 1 else (rel.split("/")[0] if "/" in rel else "(root)"), rel, o.type, hp[0] if hp else None, hp[1] if hp else None, score))
            break
    by = collections.defaultdict(list)
    for r in rows: by[r[0]].append(r)
    lines = ["# Puppet parameter table (generated)\n",
             f"Generated by `tools/re/puppet_stats.py --markdown` from the **{len(rows)} puppet parameter files** of the retail install (all patches). "
             "Columns: the file (under `Content/SeriousSam2/Databases/`), the root class, **`SPuppetHealthParams.1`** (the health), **`.2`** (second health member: 0, 100 or 999,999; meaning unknown) and "
             "**`CMiscPupeptParams.mpp_slScore`** (the score for killing it). Health values are the base values before the difficulty multiplier (`player-rules.md`).\n"]
    for group, rs in sorted(by.items()):
        lines.append(f"\n## {group} ({len(rs)})\n\n| File | Class | Health | `.2` | Score |\n|---|---|---|---|---|")
        for _, rel, cls, h, h2, sc in sorted(rs, key=lambda x: x[1]):
            lines.append(f"| `{rel.split('/', 1)[-1] if '/' in rel else rel}` | `{cls}` | {h} | {h2} | {sc} |")
    text = "\n".join(lines) + "\n"
    if md: open(md, "w", encoding="utf-8", newline="\n").write(text); print("wrote", md, len(rows), "files")
    else:
        print(text[:3000]); print(len(rows), "files")
    sc = collections.Counter(r[5] for r in rows)
    print("score distribution:", sorted(sc.items()))


if __name__ == "__main__":
    main()
