"""Class catalogue from the type tables of every CTSEMETA file (read-only; rules: docs/re/ctsemeta-types.md).

Every format-8 file carries the definitions of the classes it uses, with their base class, flags and members.
This script merges those definitions over the whole install, reports classes whose definition differs between
files (older and newer patch levels) and writes the class hierarchy as markdown.

Usage: python -I tools/re/class_catalog.py [DATA_DIR] [--markdown OUT.md] [--modules modules.json]

`--modules` takes a JSON object {class name: letters} made locally (which game modules contain the class name
as a string; see docs/re/classes.md). The script itself never reads the game's binaries (CLEANROOM.md).
"""
import collections, json, os, sys, zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ctse_values import _natural, parse, u32  # noqa: E402


def classes_of(install):
    """({name: record}, number of files). record: variants Counter[(parent, flags, member names)], files, exts."""
    cat = {}; merged = {}
    for f in sorted((f for f in os.listdir(install) if f.lower().endswith(".gro")), key=_natural):
        with zipfile.ZipFile(os.path.join(install, f)) as z:
            for i in z.infolist():
                if i.is_dir() or i.file_size < 64: continue
                with z.open(i) as fh: head = fh.read(16)
                if head[:8] == b"CTSEMETA" and u32(head, 12) == 8: merged[i.filename.lower()] = (f, i.filename)
    by_arch = collections.defaultdict(list)
    for f, name in merged.values(): by_arch[f].append(name)
    nfiles = 0
    for f, names in by_arch.items():
        with zipfile.ZipFile(os.path.join(install, f)) as z:
            for name in names:
                r = parse(z.read(name)); nfiles += 1
                ext = os.path.splitext(name)[1].lower()
                for t in r["types"].values():
                    if t.members is None: continue
                    parent = r["types"][t.parent].name if t.parent not in (None, -1, 0xffffffff) and t.parent in r["types"] else None
                    rec = cat.setdefault(t.name, {"variants": collections.Counter(), "files": 0, "exts": collections.Counter()})
                    rec["variants"][(parent, t.flags, tuple(m for m, _ in t.members))] += 1
                    rec["files"] += 1; rec["exts"][ext] += 1
    return cat, nfiles


def best(rec):
    """The most common definition (ties: the one with more members, i.e. the newer)."""
    return max(rec["variants"].items(), key=lambda kv: (kv[1], len(kv[0][2])))[0]


def tree(cat):
    kids = collections.defaultdict(list); roots = []
    for name, rec in cat.items():
        parent = best(rec)[0]
        (kids[parent] if parent in cat else roots).append(name)
    return roots, kids


def markdown(cat, nfiles, modules, path):
    roots, kids = tree(cat); out = []
    out.append("# Class catalogue of the data files (generated)\n")
    out.append(f"Generated by `tools/re/class_catalog.py --markdown` from the type tables of **{nfiles} CTSEMETA files** "
               f"(format 8, all patches merged): **{len(cat)} classes** (types with members; primitives, containers and pointers are not listed). "
               "Each line: `Class` · own members in the most common definition · number of files that define it · the three most common file extensions · "
               "`v` if more than one definition exists (older patch levels) · the **modules** whose binary contains the class name as a string "
               "(E Engine, C Core, G Sam2Game, U EngineGui, P ProcRender, S Shaders, D GfxD3D, O GfxOGL, K the EditKit editor modules; measured locally).\n")
    def line(name, depth):
        rec = cat[name]; parent, flags, members = best(rec)
        exts = ",".join(e.lstrip(".") for e, _ in rec["exts"].most_common(3))
        mark = " v%d" % len(rec["variants"]) if len(rec["variants"]) > 1 else ""
        mod = (" · " + modules.get(name, "-")) if modules else ""
        out.append("  " * depth + f"- `{name}` · {len(members)} · {rec['files']} · {exts}{mark}{mod}")
        for k in sorted(kids.get(name, [])): line(k, depth + 1)
    for r in sorted(roots): line(r, 0)
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = {a: sys.argv[sys.argv.index(a) + 1] for a in sys.argv[1:] if a in ("--markdown", "--modules")}
    args = [a for a in args if a not in flags.values()]
    install = args[0] if args and os.path.isdir(args[0]) else os.environ.get("SS2_DATA_DIR", "")
    if not install or not os.path.isdir(install): sys.exit("pass the install folder or set SS2_DATA_DIR")
    cat, nfiles = classes_of(install)
    print(f"{len(cat)} classes over {nfiles} files")
    multi = {n: r for n, r in cat.items() if len(r["variants"]) > 1}
    print("classes with more than one definition:", len(multi))
    for n, r in sorted(multi.items())[:50]:
        print("  ", n, [(v[0], v[1], len(v[2]), c) for v, c in r["variants"].most_common(4)])
    roots, kids = tree(cat)
    print("root classes:", len(roots)); print("classes whose definition changes parent between files:", sum(1 for r in cat.values() if len({v[0] for v in r["variants"]}) > 1))
    depth = {}
    def d(n, k=0):
        depth[n] = k
        for c in kids.get(n, []): d(c, k + 1)
    for r in roots: d(r)
    print("deepest chain:", max(depth.values()) + 1, "; classes by depth:", dict(collections.Counter(depth.values())))
    print("flags values:", dict(collections.Counter(best(r)[1] for r in cat.values())))
    if "--markdown" in flags:
        modules = json.load(open(flags["--modules"])) if "--modules" in flags else {}
        markdown(cat, nfiles, modules, flags["--markdown"]); print("wrote", flags["--markdown"])


if __name__ == "__main__":
    main()
